#!/usr/bin/env python3
"""Generate Adafruit-GFX fonts for the panel from Inter (OFL).

    python3 tools/mkfonts.py [--fonts /usr/share/fonts/opentype/inter]

Writes lib/panel/src/fonts/*.h. GFX fonts need one contiguous code range, so
the few non-ASCII glyphs reef units need are packed in right after '~' and
the renderer maps UTF-8 onto them (see Text.cpp, kExtras):

    0x7F °   0x80 µ   0x81 ³   0x82 ₂   0x83 —   0x84 ·   0x85 ▲   0x86 ▼

Numeric fonts (the big values) only carry ' ' .. '9' plus a few letters used
in values, which keeps the 150 px font small.
"""
import argparse
import os

import freetype

EXTRAS = ['°', 'µ', '³', '₂', '—', '·', '▲', '▼']

# name, file, pixel size, range
FONTS = [
    ('Small',  'Inter-Medium.otf',   16, 'full'),
    ('Body',   'Inter-SemiBold.otf', 21, 'full'),
    ('Head',   'Inter-Bold.otf',     28, 'full'),
    ('Label',  'Inter-SemiBold.otf', 26, 'full'),
    ('NumS',   'Inter-Bold.otf',     34, 'full'),
    ('NumM',   'Inter-Bold.otf',     54, 'num'),
    ('NumL',   'Inter-Bold.otf',     84, 'num'),
    ('NumXL',  'Inter-Bold.otf',    128, 'num'),
]


def glyph_list(kind):
    if kind == 'full':
        return [chr(c) for c in range(0x20, 0x7F)] + EXTRAS, 0x20
    # ' ' (0x20) .. '9' (0x39): space, sign, dot, digits, '-' etc.
    return [chr(c) for c in range(0x20, 0x3A)], 0x20


def render(face, ch):
    face.load_char(ch, freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_MONO)
    g = face.glyph
    bm = g.bitmap
    w, h = bm.width, bm.rows
    bits = []
    for y in range(h):
        row = bm.buffer[y * bm.pitch:(y + 1) * bm.pitch]
        for x in range(w):
            bits.append((row[x >> 3] >> (7 - (x & 7))) & 1)
    data = bytearray()
    acc, n = 0, 0
    for b in bits:
        acc = (acc << 1) | b
        n += 1
        if n == 8:
            data.append(acc)
            acc, n = 0, 0
    if n:
        data.append(acc << (8 - n))
    return data, w, h, g.advance.x >> 6, g.bitmap_left, -g.bitmap_top


def build(name, path, px, kind, out_dir):
    face = freetype.Face(path)
    face.set_pixel_sizes(0, px)
    chars, first = glyph_list(kind)
    bitmap = bytearray()
    glyphs = []
    for ch in chars:
        if not face.get_char_index(ch):
            data, w, h, adv, xo, yo = b'', 0, 0, px // 3, 0, 0
        else:
            data, w, h, adv, xo, yo = render(face, ch)
        glyphs.append((len(bitmap), w, h, adv, xo, yo, ch))
        bitmap += data
    asc = face.size.ascender >> 6
    desc = -(face.size.descender >> 6)
    y_adv = asc + desc
    sym = f'Inter{name}'
    lines = [f'// Generated by tools/mkfonts.py from {os.path.basename(path)} at {px} px. Inter: SIL OFL 1.1.',
             '#pragma once', '#include "gfxfont_compat.h"', '',
             f'const uint8_t {sym}Bitmaps[] PROGMEM = {{']
    for i in range(0, len(bitmap), 16):
        lines.append('  ' + ', '.join(f'0x{b:02X}' for b in bitmap[i:i + 16]) + ',')
    lines.append('};')
    lines.append(f'const GFXglyph {sym}Glyphs[] PROGMEM = {{')
    for off, w, h, adv, xo, yo, ch in glyphs:
        label = ch if ch.isprintable() and ch not in '\\' else hex(ord(ch))
        lines.append(f'  {{{off:6d}, {w:3d}, {h:3d}, {adv:3d}, {xo:4d}, {yo:4d}}},  // {label}')
    lines.append('};')
    last = first + len(chars) - 1
    lines.append(f'const GFXfont {sym} PROGMEM = {{(uint8_t *){sym}Bitmaps, (GFXglyph *){sym}Glyphs, 0x{first:02X}, 0x{last:02X}, {y_adv}}};')
    lines.append(f'// ascent {asc}, bitmap {len(bitmap)} bytes')
    with open(os.path.join(out_dir, f'{sym}.h'), 'w') as f:
        f.write('\n'.join(lines) + '\n')
    return sym, len(bitmap), asc


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--fonts', default='/usr/share/fonts/opentype/inter')
    here = os.path.dirname(os.path.abspath(__file__))
    ap.add_argument('--out', default=os.path.join(here, '..', 'lib', 'panel', 'src', 'fonts'))
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    total = 0
    for name, fn, px, kind in FONTS:
        sym, n, asc = build(name, os.path.join(a.fonts, fn), px, kind, a.out)
        total += n
        print(f'{sym:12s} {px:4d}px  ascent {asc:3d}  {n:6d} bytes')
    print(f'total bitmap {total} bytes')


if __name__ == '__main__':
    main()
